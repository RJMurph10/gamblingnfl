/**
 * Writes src/data/nfl/market-prior.ts: each team's end-of-season market rating (points vs an average
 * team, fit to that season's betting spreads, late-season weeks weighted 1.5x), the starting point for
 * next season's futures. Re-run once a season ends:
 *   SEASON=2026 node /root/fbdata/sitecheck/run.cjs $PWD research/football/scripts/futures_market_prior.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { marketFit } from "@/lib/nfl/futures-sim";
import { teamByAbbr } from "@/data/shared/teams";

const SEASON = Number(process.env.SEASON ?? 2025);
const ALIAS: Record<string, string> = { LA: "LAR", WAS: "WSH", OAK: "LV", SD: "LAC", STL: "LAR" };
const lines = readFileSync(process.env.CSV ?? "/root/fbdata/src/nfl_games.csv", "utf8").trim().split("\n");
const head = lines[0].split(",");
const reg = lines
  .slice(1)
  .map((l) => Object.fromEntries(head.map((h, i) => [h, l.split(",")[i]])) as Record<string, string>)
  .filter((r) => Number(r.season) === SEASON && r.game_type === "REG" && r.spread_line !== "");
const id = (abbr: string) => teamByAbbr(ALIAS[abbr] ?? abbr)!.id;
const ids = [...new Set(reg.map((r) => id(r.home_team)))];
const fit = marketFit(
  reg.map((r) => ({ h: id(r.home_team), a: id(r.away_team), spread: Number(r.spread_line), neutral: r.location === "Neutral", w: Number(r.week) >= 10 ? 1.5 : 1 })),
  ids,
  {},
  0.5,
);
const body = ids
  .sort((a, b) => fit.power[b] - fit.power[a])
  .map((t) => `  ${/^\d/.test(t) ? `"${t}"` : t}: ${fit.power[t].toFixed(2)},`)
  .join("\n");
writeFileSync(
  "src/data/nfl/market-prior.ts",
  `/**
 * Each team's market rating at the end of the ${SEASON} regular season: points better than an average
 * team on a neutral field, fit to that season's betting spreads (later weeks count 1.5x). The futures
 * simulator starts the next season from ${"60%"} of these. Generated by
 * research/football/scripts/futures_market_prior.ts — re-run after each season.
 */
export const NFL_MARKET_PRIOR_SEASON = ${SEASON};

export const NFL_MARKET_PRIOR: Record<string, number> = {
${body}
};
`,
);
console.log(`home field ${fit.hf.toFixed(2)}; ${ids.length} teams written`);
